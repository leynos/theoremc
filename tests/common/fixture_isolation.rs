//! Isolation helpers for fixture crates built by integration tests.
//!
//! Fixture crates share one warm target directory so third-party dependencies
//! compile once per run, keep their own artefacts apart through unique package
//! names, and seed their lock from a committed template. These helpers decide
//! the target directory, the Cargo home, the package name and the lock a
//! fixture starts from; `fixture_crate` owns everything else.

use std::fmt::Write;
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{SystemTime, UNIX_EPOCH};

use camino::{Utf8Path, Utf8PathBuf};
use cap_std::{ambient_authority, fs_utf8::Dir};

use super::lock_file::assigned_string;

/// Counts fixtures in this process, so package names stay unique within it.
static FIXTURE_SEQUENCE: AtomicU64 = AtomicU64::new(0);

/// The variable that names the Cargo home every fixture build shares.
pub const FIXTURE_CARGO_HOME_VARIABLE: &str = "THEOREMC_FIXTURE_CARGO_HOME";

/// The lock a generated fixture crate seeds before its first build.
///
/// Each variant names one committed template under `tests/fixtures/`. A
/// fixture's lock must describe exactly the dependency graph its generated
/// manifest declares, because the builds run `--frozen`: a lock that resolves
/// a package the graph does not use, or misses one it needs, is refused rather
/// than rewritten. Selecting the wrong template therefore fails the build
/// instead of silently re-resolving against the network.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FixtureLock {
    /// The fixture declares no dependencies, so its lock names only its root.
    DependencyFree,
    /// The fixture resolves the build-support crate and its registry graph.
    BuildSupport,
    /// The fixture resolves `theoremc`, the build-support crate and their graph.
    TheoremFileMacro,
}

impl FixtureLock {
    /// Returns the template this lock seeds from.
    const fn template(self) -> FixtureTemplate {
        match self {
            Self::DependencyFree => DEPENDENCY_FREE_TEMPLATE,
            Self::BuildSupport => BUILD_SUPPORT_TEMPLATE,
            Self::TheoremFileMacro => THEOREM_FILE_MACRO_TEMPLATE,
        }
    }
}

/// A committed fixture-template lock and the root package entry it records.
#[derive(Clone, Copy)]
struct FixtureTemplate {
    /// The template's root package name, which each fixture renames.
    root: &'static str,
    /// The template's committed lock text.
    lock: &'static str,
}

/// A lock naming only a root package, for a fixture with no dependencies.
///
/// The template's root is renamed to the fixture's package name like any
/// other, so the entry that remains is the one Cargo would write for a crate
/// that resolves nothing.
const DEPENDENCY_FREE_TEMPLATE: FixtureTemplate = FixtureTemplate {
    root: "fixture_template",
    lock: concat!(
        "# This file is automatically @generated by Cargo.\n",
        "# It is not intended for manual editing.\n",
        "version = 4\n",
        "\n",
        "[[package]]\n",
        "name = \"fixture_template\"\n",
        "version = \"0.1.0\"\n",
    ),
};

/// The lock `tests/fixtures/build_support_fixture` commits.
const BUILD_SUPPORT_TEMPLATE: FixtureTemplate = FixtureTemplate {
    root: "build_support_fixture",
    lock: include_str!("../fixtures/build_support_fixture/Cargo.lock"),
};

/// The lock `tests/fixtures/theorem_file_macro_fixture` commits.
const THEOREM_FILE_MACRO_TEMPLATE: FixtureTemplate = FixtureTemplate {
    root: "theorem_file_macro_fixture",
    lock: include_str!("../fixtures/theorem_file_macro_fixture/Cargo.lock"),
};

/// Returns the lock text a fixture named `package_name` seeds from `lock`.
///
/// The template's own root entry is renamed to the generated package name and
/// nothing else changes, so the fixture starts from the versions the workspace
/// already resolved.
///
/// # Errors
///
/// Returns an error when the template names no root entry, or names one that
/// records a source, which a registry package would.
pub fn seeded_lock(lock: FixtureLock, package_name: &str) -> Result<String, String> {
    let template = lock.template();
    with_renamed_root(template.lock, template.root, package_name)
}

/// Returns `lock` with the path entry naming `root` renamed to `name`.
///
/// A registry package always records a `source`; a template's root does not.
/// Requiring exactly one source-less entry named `root` is what keeps the
/// rename from rewriting a dependency of the same name.
///
/// # Errors
///
/// Returns an error when no entry names `root`, when more than one does, or
/// when the only candidate records a source.
fn with_renamed_root(lock: &str, root: &str, name: &str) -> Result<String, String> {
    let lines: Vec<&str> = lock.lines().collect();
    let target = root_name_line(&lines, root)?;
    let mut rendered = String::with_capacity(lock.len());
    for (index, line) in lines.iter().enumerate() {
        match index {
            _ if index == target => {
                write!(rendered, "name = \"{name}\"")
                    .map_err(|error| format!("rendering the renamed root: {error}"))?;
            }
            _ => rendered.push_str(line),
        }
        rendered.push('\n');
    }
    Ok(rendered)
}

/// Returns the line index of the source-less entry naming `root`.
///
/// # Errors
///
/// Returns an error when no entry names `root`, or when more than one does.
fn root_name_line(lines: &[&str], root: &str) -> Result<usize, String> {
    let mut found = None;
    for (start, end) in package_blocks(lines) {
        let block = lines
            .get(start..end)
            .ok_or_else(|| format!("fixture lock block {start}..{end} is out of range"))?;
        if block
            .iter()
            .any(|line| assigned_string(line.trim(), "source").is_some())
        {
            continue;
        }
        let Some(offset) = block
            .iter()
            .position(|line| assigned_string(line.trim(), "name") == Some(root))
        else {
            continue;
        };
        if found.is_some() {
            return Err(format!(
                "fixture lock names {root:?} as a root package more than once"
            ));
        }
        found = Some(start + offset);
    }
    found.ok_or_else(|| format!("fixture lock names no root package {root:?}"))
}

/// Returns the `[[package]]` blocks of a lock as `[start, end)` line ranges.
fn package_blocks(lines: &[&str]) -> Vec<(usize, usize)> {
    let starts: Vec<usize> = lines
        .iter()
        .enumerate()
        .filter(|(_, line)| line.trim() == "[[package]]")
        .map(|(index, _)| index)
        .collect();
    starts
        .iter()
        .enumerate()
        .map(|(position, start)| {
            let end = starts.get(position + 1).copied().unwrap_or(lines.len());
            (*start, end)
        })
        .collect()
}

/// Returns a short suffix that is unlikely to clash with any other fixture's.
///
/// Three parts make a clash unlikely: the process id separates processes that
/// run at once, the sequence number separates fixtures within a process, and
/// the clock's low 16 bits separate runs that reuse a process id. They do not
/// make it impossible, because the clock bits wrap; `first_unused_suffix`
/// closes that gap by refusing a suffix the shared target already holds build
/// directories for.
pub(super) fn unique_suffix() -> String {
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map_or(0, |elapsed| elapsed.as_nanos());
    let clock = u32::try_from(nanos & 0xffff).unwrap_or(0);
    let sequence = FIXTURE_SEQUENCE.fetch_add(1, Ordering::Relaxed);
    format!("{:x}_{sequence:x}_{clock:04x}", std::process::id())
}

/// Returns the first suffix `in_use` does not report as taken.
///
/// A name is taken when the shared target already holds build directories for
/// it, left by an earlier process whose id was reused. Checking the directory
/// makes a name safe by construction instead of by probability.
///
/// # Errors
///
/// Returns the first error `in_use` reports: a scan that failed cannot say a
/// name is free.
pub(super) fn first_unused_suffix(
    mut next: impl FnMut() -> String,
    mut in_use: impl FnMut(&str) -> Result<bool, String>,
) -> Result<String, String> {
    loop {
        let suffix = next();
        if !in_use(&suffix)? {
            return Ok(suffix);
        }
    }
}

/// Returns whether `target_dir` already holds build directories for `suffix`,
/// in the classic layout (`build/fx_<suffix>-<hash>`) or the newer one
/// (`build/fx_<suffix>/<hash>`).
///
/// # Errors
///
/// Returns an error when the build directory exists but cannot be read; a build
/// directory that does not exist yet holds nothing.
pub(super) fn suffix_is_taken(target_dir: &Utf8Path, suffix: &str) -> Result<bool, String> {
    let package = format!("fx_{suffix}");
    let prefix = format!("{package}-");
    let build = match Dir::open_ambient_dir(target_dir.join("debug/build"), ambient_authority()) {
        Ok(build) => build,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(false),
        Err(error) => return Err(error.to_string()),
    };
    for listing in build.entries().map_err(|error| error.to_string())? {
        let name = listing
            .and_then(|found| found.file_name())
            .map_err(|error| error.to_string())?;
        if name.starts_with(&prefix) || name == package {
            return Ok(true);
        }
    }
    Ok(false)
}

/// Reads the value of a `name = "..."` line.
fn quoted_name(line: &str) -> Option<&str> {
    let value = line
        .trim()
        .strip_prefix("name")?
        .trim_start()
        .strip_prefix('=')?
        .trim();
    value.strip_prefix('"')?.strip_suffix('"')
}

/// Names the `[package]` after *suffix* and returns the manifest and the name.
///
/// Fixtures share one target directory, so two fixtures with the same package
/// name would share build directories and a test could read another fixture's
/// generated suite. The name is short on purpose: Kani writes a file named
/// after the crate and the proof harness, and a long crate name pushed that
/// file name past the filesystem limit. Only the first `name` inside
/// `[package]` changes.
pub(super) fn with_unique_package_name(
    manifest: &str,
    suffix: &str,
) -> Result<(String, String), String> {
    let mut in_package = false;
    let mut unique = None;
    let mut lines = Vec::new();
    for line in manifest.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with('[') {
            in_package = trimmed == "[package]";
        }
        match quoted_name(line).filter(|_| in_package && unique.is_none()) {
            Some(_) => {
                let name = format!("fx_{suffix}");
                lines.push(format!("name = \"{name}\""));
                unique = Some(name);
            }
            None => lines.push(line.to_owned()),
        }
    }
    let name = unique.ok_or_else(|| "fixture manifest must name its package".to_owned())?;
    Ok((format!("{}\n", lines.join("\n")), name))
}

/// Returns the repository checkout, which is two levels above this crate.
fn repository_root() -> Utf8PathBuf {
    let crate_dir = Utf8Path::new(env!("CARGO_MANIFEST_DIR"));
    crate_dir
        .ancestors()
        .nth(2)
        .unwrap_or(crate_dir)
        .to_path_buf()
}

/// Returns the absolute target directory shared by every fixture crate.
///
/// It sits inside the caller's `CARGO_TARGET_DIR` when one is exported, else
/// inside the repository's `target`, so it is warm on a second run and `cargo
/// clean` removes it.
#[expect(
    clippy::disallowed_methods,
    reason = "fixture crates must share the target directory the host Cargo invocation is using, so the helper reads the ambient CARGO_TARGET_DIR"
)]
pub(super) fn shared_target_dir() -> Result<Utf8PathBuf, String> {
    let base = std::env::var("CARGO_TARGET_DIR")
        .map_or_else(|_| repository_root().join("target"), Utf8PathBuf::from);
    let directory = base.join("theoremc-fixture-builds");
    Dir::create_ambient_dir_all(&directory, ambient_authority())
        .map_err(|error| error.to_string())?;
    directory
        .canonicalize_utf8()
        .map_err(|error| error.to_string())
}

/// Returns the Cargo home every fixture build shares, creating it if absent.
///
/// `make fetch` populates this home and exports its path, so a nested build
/// resolves from it without touching the caller's `$CARGO_HOME`. That keeps a
/// fixture out of the shared package-cache lock, which even an offline Cargo
/// takes exclusively, and leaves the caller's target warm.
///
/// # Errors
///
/// Returns an error when the directory cannot be created.
#[expect(
    clippy::disallowed_methods,
    reason = "the fixture Cargo home is chosen by the host build (`make fetch` exports it), so the helper reads the ambient THEOREMC_FIXTURE_CARGO_HOME and otherwise falls back to the repository's target"
)]
pub fn fixture_cargo_home() -> Result<Utf8PathBuf, String> {
    let configured = std::env::var(FIXTURE_CARGO_HOME_VARIABLE).ok();
    let directory = resolved_cargo_home(configured.as_deref());
    Dir::create_ambient_dir_all(&directory, ambient_authority())
        .map_err(|error| error.to_string())?;
    Ok(directory)
}

/// Returns the Cargo home a fixture build uses when `configured` names one.
///
/// The fallback sits inside the repository's target directory, so it is warm
/// on a second run and `cargo clean` removes it with the rest of the build
/// output.
fn resolved_cargo_home(configured: Option<&str>) -> Utf8PathBuf {
    configured.map_or_else(
        || repository_root().join("target/theoremc-fixture-cargo-home"),
        Utf8PathBuf::from,
    )
}

